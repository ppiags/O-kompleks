/**
 * Детерминированная нормализация текста для локального retrieval.
 * Без внешних зависимостей: 8 статей базы знаний не требуют embeddings.
 */

const STOP_WORDS = new Set([
  'а', 'без', 'бы', 'был', 'была', 'были', 'было', 'быть', 'в', 'вам', 'вас', 'ваш', 'ваша', 'ваши',
  'ведь', 'весь', 'вот', 'все', 'вы', 'где', 'да', 'даже', 'для', 'до', 'его', 'ее', 'ей', 'если',
  'есть', 'еще', 'же', 'за', 'здесь', 'и', 'из', 'или', 'им', 'их', 'к', 'как', 'ко', 'когда', 'кто',
  'ли', 'либо', 'мне', 'может', 'можно', 'мы', 'на', 'над', 'нам', 'нас', 'наш', 'не', 'него', 'нее',
  'нет', 'ни', 'ним', 'них', 'но', 'ну', 'о', 'об', 'он', 'она', 'они', 'от', 'по', 'под', 'при', 'с',
  'сам', 'свое', 'свои', 'себя', 'так', 'такой', 'там', 'те', 'тем', 'то', 'тогда', 'того', 'тоже',
  'только', 'том', 'ты', 'у', 'уж', 'уже', 'хотим', 'хочу', 'хочет', 'чем', 'через', 'что', 'чтобы',
  'эта', 'эти', 'это', 'этот', 'я', 'здравствуйте', 'пожалуйста', 'подскажите', 'скажите', 'будет',
  'будут', 'буду',
])

const ENDINGS = [
  'иями', 'ями', 'ами', 'ией', 'иях', 'иям', 'ием', 'ого', 'ему', 'ыми', 'ими',
  'ей', 'ой', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ов', 'ев', 'ах', 'ях',
  'ам', 'ям', 'ом', 'ем', 'ую', 'юю', 'ию', 'ия', 'ии', 'ать', 'ять', 'еть', 'ить',
  'ешь', 'ишь', 'ует', 'уют', 'ают', 'ит', 'ат', 'ят', 'ут', 'ют', 'ла', 'ло', 'ли',
  'ть', 'ся', 'ы', 'и', 'а', 'я', 'о', 'е', 'у', 'ю', 'ь',
].sort((a, b) => b.length - a.length)

/** Приводит текст к нижнему регистру, заменяет ё→е и убирает пунктуацию. */
export function normalizeText(input: string): string {
  return input
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/** Грубое усечение русских окончаний: достаточно для сопоставления запроса и статей. */
function stem(token: string): string {
  for (const ending of ENDINGS) {
    if (token.endsWith(ending) && token.length - ending.length >= 4) {
      return token.slice(0, token.length - ending.length)
    }
  }
  return token
}

/** Токенизирует текст: нормализация, стемминг, отбрасывание стоп-слов и дубликатов. */
export function tokenize(input: string): string[] {
  const seen = new Set<string>()
  const tokens: string[] = []

  for (const raw of normalizeText(input).split(' ')) {
    if (raw.length === 0) continue
    if (STOP_WORDS.has(raw)) continue
    const token = stem(raw)
    if (token.length < 2) continue
    if (STOP_WORDS.has(token)) continue
    if (seen.has(token)) continue
    seen.add(token)
    tokens.push(token)
  }

  return tokens
}
